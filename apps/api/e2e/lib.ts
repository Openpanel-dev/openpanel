// ── Auth-cache warming and the scrypt outlier ───────────────────────────────
/**
 * Why warming matters: `client-auth.ts` shields `verifyPassword` behind
 * `VERIFY_CACHE_SECONDS = 300`, so a scrypt is a LATENCY OUTLIER, not a
 * per-request cost. A rung shorter than the TTL pays it once, at whatever
 * moment it happens to fall. Paying it before recording starts is what stops
 * a knee from being an artefact of a scrypt spike landing mid-rung.
 */
export const AUTH_WARM_REQUESTS = Number.parseInt(
  process.env.E2E_AUTH_WARM_REQUESTS || '3',
  10
);

/** Warm/probe traffic lives outside the 100.x space the session ids use. */
const WARM_IP = '203.0.113.7';
const PROBE_IP = '203.0.113.8';

export interface AuthWarmResult {
  mode: AuthMode;
  requests: number;
  latenciesMs: number[];
  maxMs: number | null;
}

/** One raw /track round-trip that reports its status instead of throwing. */
async function timedTrack(
  headers: Record<string, string>,
  ip: string
): Promise<{ status: number; ms: number }> {
  const startedAt = performance.now();
  const res = await fetch(`${API_URL}/track`, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      ...headers,
      'user-agent': UA,
      'x-client-ip': ip,
    },
    body: JSON.stringify({
      type: 'track',
      payload: {
        name: 'screen_view',
        properties: { __path: 'https://e2e.test/warm', __ip: ip },
      },
    }),
  });
  await res.text();
  return { status: res.status, ms: performance.now() - startedAt };
}

/**
 * Send and DISCARD `requests` authenticated requests so the auth verdict is
 * resident before the measured phase starts. Latencies are returned so the
 * caller can show where the scrypt landed.
 */
export async function warmAuthCache(
  mode: AuthMode = AUTH_MODE,
  requests: number = AUTH_WARM_REQUESTS
): Promise<AuthWarmResult> {
  const latenciesMs: number[] = [];
  const headers = authHeaders(mode);
  for (let i = 0; i < requests; i++) {
    const { status, ms } = await timedTrack(headers, WARM_IP);
    if (status < 200 || status >= 300) {
      throw new Error(
        `auth warm-up rejected (${status}) in mode "${mode}" — the fixture for this auth path is wrong, not the load`
      );
    }
    latenciesMs.push(ms);
  }
  return {
    mode,
    requests,
    latenciesMs,
    maxMs: latenciesMs.length ? Math.max(...latenciesMs) : null,
  };
}

export interface AuthCostProbe {
  coldMs: number;
  coldStatus: number;
  warmMs: number;
  warmStatus: number;
  scryptMs: number;
}

/**
 * Measure what the TTL is hiding: one request whose secret has never been seen
 * (guaranteed L1+L2 miss, so a real scrypt runs and is then refused) against
 * one on the warmed real secret. The delta is the outlier a mid-rung cache
 * expiry would inject.
 */
export async function probeAuthCost(): Promise<AuthCostProbe> {
  const neverSeenSecret = `e2e-cold-${Date.now()}-${Math.random().toString(36).slice(2)}`;
  const cold = await timedTrack(
    {
      'openpanel-client-id': SECRET_CLIENT_ID,
      'openpanel-client-secret': neverSeenSecret,
    },
    PROBE_IP
  );
  const warm = await timedTrack(authHeaders('secret'), PROBE_IP);
  return {
    coldMs: cold.ms,
    coldStatus: cold.status,
    warmMs: warm.ms,
    warmStatus: warm.status,
    scryptMs: cold.ms - warm.ms,
  };
}

