// ── ClickHouse counting (scoped to a set of session ids for run isolation) ──
const quoteList = (ids: string[]) =>
  ids.map((id) => `'${id.replace(/'/g, '')}'`).join(',');

export async function countByName(
  sessionIds: string[],
  name: string
): Promise<number> {
  if (sessionIds.length === 0) {
    return 0;
  }
  const rows = await chQuery<{ c: string }>(
    `SELECT count() AS c FROM events WHERE project_id = '${PROJECT_ID}' AND name = '${name}' AND session_id IN (${quoteList(sessionIds)})`
  );
  return Number(rows[0]?.c ?? 0);
}

// ── Fixtures ────────────────────────────────────────────────────────────────
export async function ensureFixtures() {
  scenario('setup: project + client');
  try {
    await db.organization.upsert({
      where: { id: ORG_ID },
      create: { id: ORG_ID, name: 'OpenPanel Dev' },
      update: {},
    });
    await db.project.upsert({
      where: { id: PROJECT_ID },
      create: {
        id: PROJECT_ID,
        name: 'E2E Sessions',
        organizationId: ORG_ID,
        cors: [CORS_DOMAIN],
      },
      // The allow-list is what makes auth path (b) reachable; the bypass
      // client returns before the CORS check, so this changes nothing for it.
      update: { cors: [CORS_DOMAIN] },
    });
    await db.client.upsert({
      where: { id: CLIENT_ID },
      create: {
        id: CLIENT_ID,
        name: 'e2e',
        organizationId: ORG_ID,
        projectId: PROJECT_ID,
        type: ClientType.write,
        ignoreCorsAndSecret: true,
        secret: null,
      },
      update: { ignoreCorsAndSecret: true, projectId: PROJECT_ID },
    });
    // `hashPassword` here is @openpanel/shared/server's scrypt hash, re-exported
    // by @openpanel/core under its own name (core/src/index.ts) — reached that
    // way because apps/api does not declare @openpanel/shared, and adding it
    // would move the lockfile.
    const secret = await hashPassword(CLIENT_SECRET);
    await db.client.upsert({
      where: { id: SECRET_CLIENT_ID },
      create: {
        id: SECRET_CLIENT_ID,
        name: 'e2e-secret',
        organizationId: ORG_ID,
        projectId: PROJECT_ID,
        type: ClientType.write,
        ignoreCorsAndSecret: false,
        secret,
      },
      update: {
        ignoreCorsAndSecret: false,
        projectId: PROJECT_ID,
        secret,
      },
    });
    await getClientByIdCached.clear({ db }, CLIENT_ID);
    await getClientByIdCached.clear({ db }, SECRET_CLIENT_ID);
    check('fixtures ready', true);
  } catch (error) {
    check('fixtures ready', false, (error as Error).message);
    throw error;
  }
}

export async function preflight() {
  scenario('preflight');
  const api = await fetch(`${API_URL}/`)
    .then((r) => r.ok || r.status === 404)
    .catch(() => false);
  check(`api reachable at ${API_URL}`, !!api);
  const worker = await fetch(`${WORKER_URL}/debug/cron`)
    .then((r) => r.ok)
    .catch(() => false);
  check(`worker debug reachable at ${WORKER_URL}`, !!worker);
  if (!(api && worker)) {
    throw new Error('Stack not reachable — start it with `pnpm dev` first.');
  }
  if (SESSION_TIMEOUT_MS > 60_000) {
    console.warn(
      `\n⚠ SESSION_TIMEOUT_MS=${SESSION_TIMEOUT_MS}ms — this run will be slow.\n` +
        '  Re-run the stack AND the harness with e.g. SESSION_TIMEOUT_MS=4000.'
    );
  }
}

/** Run `fn` over `items` with at most `concurrency` in flight. */
export async function runPool<T>(
  items: T[],
  concurrency: number,
  fn: (item: T, index: number) => Promise<void>
): Promise<void> {
  let next = 0;
  const workers = Array.from(
    { length: Math.min(concurrency, items.length) },
    async () => {
      while (true) {
        const i = next++;
        if (i >= items.length) {
          return;
        }
        await fn(items[i]!, i);
      }
    }
  );
  await Promise.all(workers);
}

export async function shutdown(failed: number): Promise<never> {
  await redis.quit().catch(() => {});
  process.exit(failed ? 1 : 0);
}
